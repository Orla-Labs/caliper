"""Shared plumbing for compile targets: grader source loading, dataset I/O,
deterministic file writing, and rendering of self-contained Python artifacts.

Determinism contract: every emitted byte depends only on the grader source,
the selected attribute, the grader file's *basename*, and the dataset rows (in
input order). No timestamps, absolute paths, or environment details.
"""

from __future__ import annotations

import ast
import hashlib
import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from caliper_sdk import EvalRow

from caliper_rft.targets import _shim

_HERE = Path(__file__).parent


class CompileError(Exception):
    """User-facing error (bad grader spec, bad dataset row, ...)."""


@dataclass(frozen=True)
class GraderSource:
    """A grader file's source plus which `@grader` in it to use."""

    source: str
    attr: str
    filename: str  # basename only, embedded in emitted artifacts
    name: str  # the grader's `.name` (what trainers log it as)

    @classmethod
    def from_source(cls, source: str, attr: str | None, filename: str) -> GraderSource:
        """Validate by loading through the SAME shim the emitted artifacts use."""
        source = source.replace("\r\n", "\n")
        try:
            namespace = _shim.exec_grader_source(source, filename)
            if attr is None:
                found = _shim.grader_names(namespace)
                if len(found) != 1:
                    raise CompileError(
                        f"{filename} defines {len(found)} graders ({', '.join(found)}); "
                        "select one with PATH.py:ATTR"
                    )
                attr = found[0]
            g = _shim.load_grader(source, attr, filename)
        except CompileError:
            raise
        except SyntaxError as e:
            raise CompileError(f"{filename}: syntax error at line {e.lineno}: {e.msg}") from e
        except Exception as e:
            raise CompileError(f"{filename}: cannot load grader: {type(e).__name__}: {e}") from e
        return cls(source=source, attr=attr, filename=filename, name=str(g.name))

    @classmethod
    def from_spec(cls, spec: str) -> GraderSource:
        """Parse `PATH.py:ATTR` (or `PATH.py` when the file has exactly one grader)."""
        path_s, attr = spec, None
        head, sep, tail = spec.rpartition(":")
        if sep and tail.isidentifier():
            path_s, attr = head, tail
        path = Path(path_s)
        if not path.is_file():
            raise CompileError(f"grader file not found: {path_s}")
        return cls.from_source(path.read_text(encoding="utf-8"), attr, path.name)


def load_dataset(path: str | Path) -> list[EvalRow]:
    """Read EvalRow JSONL (blank lines skipped). Order is preserved."""
    p = Path(path)
    if not p.is_file():
        raise CompileError(f"dataset not found: {path}")
    rows: list[EvalRow] = []
    for lineno, line in enumerate(p.read_text(encoding="utf-8").splitlines(), start=1):
        if not line.strip():
            continue
        try:
            rows.append(EvalRow.model_validate_json(line))
        except Exception as e:
            raise CompileError(f"{p.name}:{lineno}: not a valid EvalRow: {e}") from e
    if not rows:
        raise CompileError(f"dataset {p.name} has no rows")
    return rows


def dumps(obj: Any) -> str:
    """Canonical JSON used for every emitted record."""
    return json.dumps(obj, sort_keys=True, ensure_ascii=False)


def write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.encode("utf-8"))


def write_jsonl(path: Path, records: list[dict[str, Any]]) -> None:
    write_text(path, "".join(dumps(r) + "\n" for r in records))


def py_str_literal(s: str) -> str:
    """Readable Python literal for `s` (raw triple-quoted when safe, else repr)."""
    candidate = "r'''" + s + "'''"
    if "'''" not in s and not s.endswith(("\\", "'")):
        try:
            if ast.literal_eval(candidate) == s:
                return candidate
        except (SyntaxError, ValueError):
            pass
    return repr(s)


def _embedded(module_file: str) -> str:
    return (_HERE / module_file).read_text(encoding="utf-8").replace("\r\n", "\n").rstrip() + "\n"


def render_artifact(*, target: str, grader: GraderSource, on_error: float | None, tail: str,
                    docstring: str) -> str:
    """Render a self-contained Python file: shim + runtime + grader source + tail."""
    digest = hashlib.sha256(grader.source.encode("utf-8")).hexdigest()
    parts = [
        f'"""{docstring.strip()}\n"""\n',
        f"# Generated by caliper-compile --target {target}. Do not edit by hand; re-run\n"
        f"# caliper-compile instead. Requires only the Python standard library (>= 3.10).\n"
        f"# grader: {grader.filename}:{grader.attr} (name={grader.name!r})\n"
        f"# grader source sha256: {digest}\n",
        _embedded("_shim.py"),
        _embedded("_runtime.py"),
        "# ---------------------------------------------------------------------------\n"
        f"# grader source, verbatim from {grader.filename}\n"
        "# ---------------------------------------------------------------------------\n"
        f"GRADER_SOURCE = {py_str_literal(grader.source)}\n"
        f"GRADER_ATTR = {grader.attr!r}\n"
        f"GRADER_NAME = {grader.name!r}\n"
        f"# Score assigned when the grader raises or returns an invalid score.\n"
        f"ON_ERROR = {on_error!r}\n"
        f"GRADER = load_grader(GRADER_SOURCE, GRADER_ATTR, {grader.filename!r})\n",
        tail.strip() + "\n",
    ]
    return "\n\n".join(parts)


def rel_display(out_arg: str, name: str) -> str:
    """Path shown in the CLI summary: as the user typed --out, never absolutised."""
    return (Path(out_arg) / name).as_posix()
